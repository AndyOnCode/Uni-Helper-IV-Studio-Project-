package ec.edu.espe.ivstudio.unihelper.model;

/**
 *
 * @author Danilo Simba, @ESPE
 */
public class CalendarEvent {
    private String title;
    private String date;
    private String time;
    private String description;
    
    public CalendarEvent(){
        
    }    

    public CalendarEvent(String title, String date, String time, String description) {
        this.title = title;
        this.date = date;
        this.time = time;
        this.description = description;
    }

    /**
     * @return the title
     */
    public String getTitle() {
        return title;
    }

    /**
     * @param title the title to set
     */
    public void setTitle(String title) {
        this.title = title;
    }

    /**
     * @return the date
     */
    public String getDate() {
        return date;
    }

    /**
     * @param date the date to set
     */
    public void setDate(String date) {
        this.date = date;
    }

    /**
     * @return the time
     */
    public String getTime() {
        return time;
    }

    /**
     * @param time the time to set
     */
    public void setTime(String time) {
        this.time = time;
    }

    /**
     * @return the description
     */
    public String getDescription() {
        return description;
    }

    /**
     * @param description the description to set
     */
    public void setDescription(String description) {
        this.description = description;
    }

    @Override
    public String toString() {
        return "CalendarEvent{" + "title=" + title + ", date=" + date + ", time=" + time + ", description=" + description + '}';
    }
    
    
}
